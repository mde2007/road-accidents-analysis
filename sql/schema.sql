CREATE TABLE IF NOT EXISTS collisions (
    collision_index TEXT PRIMARY KEY,
    collision_year INTEGER,
    collision_ref_no TEXT,
    location_easting_osgr DOUBLE PRECISION,
    location_northing_osgr DOUBLE PRECISION,
    longitude DOUBLE PRECISION,
    latitude DOUBLE PRECISION,
    police_force INTEGER,
    collision_severity TEXT,
    number_of_vehicles INTEGER,
    number_of_casualties INTEGER,
    date DATE,
    day_of_week INTEGER,
    time TIME,
    local_authority_district INTEGER,
    local_authority_ons_district TEXT,
    local_authority_highway TEXT,
    local_authority_highway_current TEXT,
    first_road_class INTEGER,
    first_road_number INTEGER,
    road_type TEXT,
    speed_limit INTEGER,
    junction_detail_historic INTEGER,
    junction_detail INTEGER,
    junction_control INTEGER,
    second_road_class INTEGER,
    second_road_number INTEGER,
    pedestrian_crossing_human_control_historic INTEGER,
    pedestrian_crossing_physical_facilities_historic INTEGER,
    pedestrian_crossing INTEGER,
    light_conditions TEXT,
    weather_conditions TEXT,
    road_surface_conditions TEXT,
    special_conditions_at_site INTEGER,
    carriageway_hazards_historic INTEGER,
    carriageway_hazards INTEGER,
    urban_or_rural_area TEXT,
    did_police_officer_attend_scene_of_accident INTEGER,
    trunk_road_flag INTEGER,
    lsoa_of_accident_location TEXT,
    enhanced_severity_collision INTEGER,
    collision_injury_based INTEGER,
    collision_adjusted_severity_serious DOUBLE PRECISION,
    collision_adjusted_severity_slight DOUBLE PRECISION,

    datetime TIMESTAMP,
    year INTEGER,
    month INTEGER,
    hour INTEGER,
    weekday_pd INTEGER,
    is_weekend BOOLEAN,
    part_of_day TEXT,
    has_coords BOOLEAN,
    driver_age_min DOUBLE PRECISION,
    driver_age_max DOUBLE PRECISION,
    driver_age_mean DOUBLE PRECISION,
    casualty_age_min DOUBLE PRECISION,
    casualty_age_max DOUBLE PRECISION,
    casualty_age_mean DOUBLE PRECISION
);

CREATE TABLE IF NOT EXISTS vehicles (
    collision_index TEXT NOT NULL,
    collision_year INTEGER,
    collision_ref_no TEXT,
    vehicle_reference INTEGER NOT NULL,
    vehicle_type INTEGER,
    towing_and_articulation INTEGER,
    vehicle_manoeuvre_historic INTEGER,
    vehicle_manoeuvre INTEGER,
    vehicle_direction_from INTEGER,
    vehicle_direction_to INTEGER,
    vehicle_location_restricted_lane_historic INTEGER,
    vehicle_location_restricted_lane INTEGER,
    junction_location INTEGER,
    skidding_and_overturning INTEGER,
    hit_object_in_carriageway INTEGER,
    vehicle_leaving_carriageway INTEGER,
    hit_object_off_carriageway INTEGER,
    first_point_of_impact INTEGER,
    vehicle_left_hand_drive INTEGER,
    journey_purpose_of_driver_historic INTEGER,
    journey_purpose_of_driver INTEGER,
    sex_of_driver INTEGER,
    age_of_driver INTEGER,
    age_band_of_driver INTEGER,
    engine_capacity_cc INTEGER,
    propulsion_code INTEGER,
    age_of_vehicle INTEGER,
    generic_make_model TEXT,
    driver_imd_decile INTEGER,
    lsoa_of_driver TEXT,
    escooter_flag INTEGER,
    driver_distance_banding INTEGER,
    PRIMARY KEY (collision_index, vehicle_reference),
    FOREIGN KEY (collision_index)
        REFERENCES collisions(collision_index)
);

CREATE TABLE IF NOT EXISTS casualties (
    collision_index TEXT NOT NULL,


    collision_year INTEGER,
    collision_ref_no TEXT,
    vehicle_reference INTEGER,
    casualty_reference INTEGER NOT NULL,
    casualty_class INTEGER,
    sex_of_casualty INTEGER,
    age_of_casualty INTEGER,
    age_band_of_casualty INTEGER,
    casualty_severity INTEGER,
    pedestrian_location INTEGER,
    pedestrian_movement INTEGER,
    car_passenger INTEGER,
    bus_or_coach_passenger INTEGER,
    pedestrian_road_maintenance_worker INTEGER,
    casualty_type INTEGER,
    casualty_imd_decile INTEGER,
    lsoa_of_casualty TEXT,
    enhanced_casualty_severity INTEGER,
    casualty_injury_based INTEGER,
    casualty_adjusted_severity_serious DOUBLE PRECISION,
    casualty_adjusted_severity_slight DOUBLE PRECISION,
    casualty_distance_banding INTEGER,
    escooter_flag INTEGER,

    PRIMARY KEY (collision_index, casualty_reference),
    FOREIGN KEY (collision_index)
        REFERENCES collisions(collision_index)
);